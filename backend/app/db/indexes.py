from pymongo import ASCENDING, DESCENDING


def ensure_indexes(db):
    db.users.create_index("email", unique=True)
    db.organizations.create_index("name")
    db.users.create_index("org_id")
    db.farms.create_index([("org_id", ASCENDING), ("code", ASCENDING)])
    db.customers.create_index([("org_id", ASCENDING), ("name", ASCENDING)])
    db.varieties.create_index([("org_id", ASCENDING), ("name", ASCENDING)])
    db.rooms.create_index([("farm_id", ASCENDING), ("code", ASCENDING)])
    db.batches.create_index("code", unique=True)
    db.batches.create_index([("farm_id", ASCENDING), ("stage", ASCENDING)])
    db.stage_history.create_index([("batch_id", ASCENDING), ("at", ASCENDING)])
    db.observations.create_index([("batch_id", ASCENDING), ("date", DESCENDING)])
    db.harvests.create_index("code", unique=True)
    db.harvests.create_index([("farm_id", ASCENDING), ("status", ASCENDING), ("date", DESCENDING)])
    db.harvests.create_index([("batch_id", ASCENDING), ("flush", ASCENDING)])
    db.stock_lots.create_index([("farm_id", ASCENDING), ("variety_id", ASCENDING), ("harvest_date", ASCENDING)])
    db.inventory_items.create_index([("farm_id", ASCENDING), ("sku", ASCENDING)])
    db.inventory_transactions.create_index([("farm_id", ASCENDING), ("created_at", DESCENDING)])
    db.sales.create_index("number", unique=True)
    db.sales.create_index([("farm_id", ASCENDING), ("date", DESCENDING)])
    db.sales.create_index("customer_id")
    db.expenses.create_index([("farm_id", ASCENDING), ("date", DESCENDING)])
    db.employees.create_index("farm_id")
    db.tasks.create_index([("farm_id", ASCENDING), ("due_date", ASCENDING)])
    db.notifications.create_index([("farm_id", ASCENDING), ("created_at", DESCENDING)])
    db.audit_logs.create_index([("created_at", DESCENDING)])
    db.token_blocklist.create_index("jti", unique=True)
    db.token_blocklist.create_index("created_at", expireAfterSeconds=60 * 60 * 24 * 30)
